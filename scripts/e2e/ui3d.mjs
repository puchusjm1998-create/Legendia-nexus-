// E2E: sinergias en Equipo y visor 3D de la ficha.
import { launch, sleep, clickText } from "./browser.mjs";
import fs from "node:fs";
const BASE = process.env.GAME_URL || "http://localhost:3000";
const SHOTS = process.env.SHOTS || "/tmp/shots"; fs.mkdirSync(SHOTS, { recursive: true });
let failures = 0;
const ok = (c, m) => { if (!c) { failures++; console.error("✗ " + m); } else console.log("✓ " + m); };
const res = await fetch(`${BASE}/api/auth/register`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ username: "ui" + Math.random().toString(36).slice(2, 8), password: "secret123" }) });
const token = (await res.json()).token;
const { browser, page } = await launch({ width: 420, height: 800 });
await page.goto(BASE, { waitUntil: "networkidle2" });
await page.evaluate((t) => localStorage.setItem("legendia_token", t), token);
await page.reload({ waitUntil: "networkidle2" });
await page.waitForFunction(() => document.body.textContent.includes("Centro de mando"), { timeout: 30000 });
const nav = (l) => page.evaluate((l) => { const b = [...document.querySelectorAll("nav button")].find((x) => x.textContent.includes(l)); b && b.click(); }, l);
await nav("Equipo"); await sleep(800);
const syn = await page.evaluate(() => document.querySelector('[data-testid="synergies"]')?.textContent || "");
console.log("  sinergias:", syn.slice(0, 200));
ok(/Sinergias activas/.test(syn) && /Vínculo|Resonancia|Frente|Eclipse|Tres/.test(syn), "Equipo muestra las sinergias activas del equipo");
await page.screenshot({ path: SHOTS + "/team.png" });
await nav("Álbum"); await sleep(800);
await page.mouse.click(210, 500);
await sleep(600);
await clickText(page, "Modelo 3D").catch(() => {});
await sleep(2500);
const canvas = await page.evaluate(() => !!document.querySelector("canvas"));
ok(canvas, "el visor 3D de la ficha crea un canvas WebGL");
await page.screenshot({ path: SHOTS + "/viewer.png" });
await browser.close();
process.exit(failures ? 1 : 0);
